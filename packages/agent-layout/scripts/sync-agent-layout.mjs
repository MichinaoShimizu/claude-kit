#!/usr/bin/env node

import {
  copyFileSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readlinkSync,
  readdirSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const args = process.argv.slice(2);
const INIT = args.includes('--init');
const WRITE = INIT || args.includes('--write');
const ROOT = resolve(
  process.cwd(),
  args.find((arg) => arg.startsWith('--root='))?.slice('--root='.length) ?? '.',
);
const GENERATED = 'Generated by agent-layout. Edit .agents/agents/ and run sync-agent-layout.mjs --write.';
const issues = [];
const actions = [];
const CI_WORKFLOW = `name: agent-layout\n\non:\n  pull_request:\n  push:\n    branches:\n      - main\n\npermissions:\n  contents: read\n\njobs:\n  agent-layout:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n      - uses: actions/setup-node@v4\n        with:\n          node-version: 22\n      - run: node scripts/sync-agent-layout.mjs\n`;

function issue(message) {
  issues.push(message);
}

function action(message) {
  actions.push(message);
}

function isSymlink(path) {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

function pathEntryExists(path) {
  try {
    lstatSync(path);
    return true;
  } catch {
    return false;
  }
}

function filesUnder(dir, suffix = '') {
  if (!existsSync(dir) || isSymlink(dir)) return [];
  const hits = [];
  const walk = (current) => {
    for (const name of readdirSync(current)) {
      const full = join(current, name);
      const stat = lstatSync(full);
      if (stat.isDirectory()) walk(full);
      else if (stat.isFile() && (!suffix || name.endsWith(suffix))) hits.push(full);
    }
  };
  walk(dir);
  return hits.sort();
}

function sameFile(a, b) {
  return existsSync(a) && readFileSync(a).equals(readFileSync(b));
}

function normalizeSkills() {
  const canonical = join(ROOT, '.agents/skills');
  const aliases = [
    [join(ROOT, '.claude/skills'), '../.agents/skills'],
    [join(ROOT, '.kiro/skills'), '../.agents/skills'],
  ];

  const seen = new Map();
  for (const dir of [canonical, ...aliases.map(([alias]) => alias)]) {
    if (!pathEntryExists(dir) || isSymlink(dir)) continue;
    for (const source of filesUnder(dir)) {
      const rel = relative(dir, source);
      const previous = seen.get(rel);
      if (previous && !sameFile(previous, source)) {
        issue(`スキルの内容が競合: ${relative(ROOT, previous)} と ${relative(ROOT, source)}`);
      } else if (!previous) {
        seen.set(rel, source);
      }
    }
  }
  if (issues.length > 0) return;

  if (!WRITE) {
    if (!existsSync(canonical)) issue('.agents/skills がない');
    for (const [alias, expected] of aliases) {
      if (!isSymlink(alias) || readlinkSync(alias) !== expected) {
        issue(`${relative(ROOT, alias)} が ${expected} へのシンボリックリンクではない`);
      }
    }
    return null;
  }
  return { canonical, aliases };
}

function applySkillPlan(plan) {
  if (!plan) return;
  const { canonical, aliases } = plan;
  mkdirSync(canonical, { recursive: true });
  for (const [alias, expected] of aliases) {
    if (pathEntryExists(alias) && !isSymlink(alias)) {
      for (const source of filesUnder(alias)) {
        const target = join(canonical, relative(alias, source));
        mkdirSync(dirname(target), { recursive: true });
        if (!existsSync(target)) copyFileSync(source, target);
      }
      rmSync(alias, { recursive: true, force: true });
      action(`${relative(ROOT, alias)} のスキルを .agents/skills へ移動`);
    } else if (isSymlink(alias) && readlinkSync(alias) !== expected) {
      rmSync(alias);
    }
    mkdirSync(dirname(alias), { recursive: true });
    if (!pathEntryExists(alias)) {
      symlinkSync(expected, alias, 'dir');
      action(`${relative(ROOT, alias)} を互換リンクに変更`);
    }
  }
}

function initWorkflowPlan() {
  if (!INIT) return null;
  const path = join(ROOT, '.github/workflows/agent-layout.yml');
  if (existsSync(path)) {
    if (readFileSync(path, 'utf8') !== CI_WORKFLOW) {
      issue(`${relative(ROOT, path)} は既存ファイルなので上書きしない`);
    }
    return null;
  }
  return { path, content: CI_WORKFLOW };
}

function unquote(value) {
  const text = value.trim();
  if ((text.startsWith('"') && text.endsWith('"')) || (text.startsWith("'") && text.endsWith("'"))) {
    return text.slice(1, -1);
  }
  return text;
}

function parseTools(value) {
  const text = value.trim().replace(/^\[/, '').replace(/\]$/, '');
  if (!text) return [];
  return text.split(',').map((item) => unquote(item.trim())).filter(Boolean);
}

const CLAUDE_TO_CAPABILITY = new Map([
  ['read', 'read'], ['grep', 'read'], ['glob', 'read'],
  ['write', 'write'], ['edit', 'write'], ['notebookedit', 'write'],
  ['bash', 'shell'], ['webfetch', 'web'], ['websearch', 'web'], ['agent', 'subagent'],
]);
const KIRO_CAPABILITIES = new Set(['read', 'write', 'shell', 'web', 'subagent']);

function parseAgentMarkdown(path, provider) {
  const text = readFileSync(path, 'utf8');
  const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) throw new Error('YAML frontmatterがない');
  const values = {};
  for (const line of match[1].split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const field = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (!field) throw new Error(`解析できないfrontmatter行: ${line}`);
    values[field[1]] = field[2];
  }
  const allowed = provider === 'claude'
    ? new Set(['name', 'description', 'tools', 'model', 'color'])
    : new Set(['name', 'description', 'tools', 'model']);
  const unsupported = Object.keys(values).filter((key) => !allowed.has(key));
  if (unsupported.length) throw new Error(`未対応のfrontmatter項目: ${unsupported.join(', ')}`);
  if (!values.name || !values.description) throw new Error('nameとdescriptionが必要');
  const name = unquote(values.name);
  if (!/^[a-z][a-z0-9_-]*$/.test(name)) {
    throw new Error('nameは英小文字で始まる英小文字・数字・ハイフン・アンダースコアに限定する');
  }

  const rawTools = values.tools === undefined ? ['*'] : parseTools(values.tools);
  const capabilities = new Set();
  for (const tool of rawTools) {
    const normalized = tool.toLowerCase();
    if (normalized === '*' || normalized === '@builtin') {
      capabilities.clear();
      capabilities.add('*');
      break;
    }
    const capability = provider === 'claude'
      ? CLAUDE_TO_CAPABILITY.get(normalized.replace(/\(.*$/, ''))
      : (KIRO_CAPABILITIES.has(normalized) ? normalized : undefined);
    if (!capability) throw new Error(`変換できないtools項目: ${tool}`);
    capabilities.add(capability);
  }

  const spec = {
    version: 1,
    name,
    description: unquote(values.description),
    instructions: match[2].trim() + '\n',
    capabilities: [...capabilities].sort(),
  };
  if (provider === 'claude' && values.model) {
    spec.providers = { claude: { model: unquote(values.model) } };
  }
  if (provider === 'claude' && values.color) {
    spec.providers ??= {};
    spec.providers.claude ??= {};
    spec.providers.claude.color = unquote(values.color);
  }
  if (provider === 'kiro' && values.model) {
    spec.providers = { kiro: { model: unquote(values.model) } };
  }
  return spec;
}

function readSpecs(dir) {
  const specs = new Map();
  for (const path of filesUnder(dir, '.json')) {
    const spec = JSON.parse(readFileSync(path, 'utf8'));
    const validCapabilities = Array.isArray(spec.capabilities)
      && spec.capabilities.every((item) => item === '*' || KIRO_CAPABILITIES.has(item))
      && !(spec.capabilities.includes('*') && spec.capabilities.length > 1);
    if (
      spec.version !== 1
      || !/^[a-z][a-z0-9_-]*$/.test(spec.name ?? '')
      || typeof spec.description !== 'string'
      || typeof spec.instructions !== 'string'
      || !validCapabilities
    ) {
      issue(`正本の形式が不正: ${relative(ROOT, path)}`);
      continue;
    }
    if (specs.has(spec.name)) issue(`エージェント名が重複: ${spec.name}`);
    specs.set(spec.name, { spec, path });
  }
  return specs;
}

function importNewAgents(specs) {
  const sources = [
    ['claude', join(ROOT, '.claude/agents')],
    ['kiro', join(ROOT, '.kiro/agents')],
  ];
  const pending = new Map();
  const adoptedPaths = new Set();
  const writes = [];
  for (const [provider, dir] of sources) {
    for (const path of filesUnder(dir, '.md')) {
      let spec;
      try {
        spec = parseAgentMarkdown(path, provider);
      } catch (error) {
        issue(`${relative(ROOT, path)}: ${error.message}`);
        continue;
      }
      if (specs.has(spec.name)) continue;
      if (pending.has(spec.name)) {
        issue(`複数の入口に未登録エージェントがある: ${spec.name}`);
        continue;
      }
      pending.set(spec.name, { spec, path });
    }
  }

  for (const [name, imported] of pending) {
    const { spec, path: sourcePath } = imported;
    const target = join(ROOT, '.agents/agents', `${name}.json`);
    if (!WRITE) {
      issue(`${name} が .agents/agents に取り込まれていない`);
      continue;
    }
    writes.push({ target, content: JSON.stringify(spec, null, 2) + '\n', name });
    specs.set(name, { spec, path: target });
    adoptedPaths.add(sourcePath);
  }
  return { adoptedPaths, writes };
}

function claudeOutput(spec) {
  const lines = ['---', `name: ${spec.name}`, `description: ${JSON.stringify(spec.description)}`];
  if (!(spec.capabilities.length === 1 && spec.capabilities[0] === '*')) {
    const tools = [];
    if (spec.capabilities.includes('read')) tools.push('Read', 'Grep', 'Glob');
    if (spec.capabilities.includes('write')) tools.push('Write', 'Edit');
    if (spec.capabilities.includes('shell')) tools.push('Bash');
    if (spec.capabilities.includes('web')) tools.push('WebFetch', 'WebSearch');
    if (spec.capabilities.includes('subagent')) tools.push('Agent');
    lines.push(`tools: ${tools.join(', ')}`);
  }
  if (spec.providers?.claude?.model) lines.push(`model: ${spec.providers.claude.model}`);
  if (spec.providers?.claude?.color) lines.push(`color: ${spec.providers.claude.color}`);
  lines.push('---', '', `<!-- ${GENERATED} -->`, '', spec.instructions.trim(), '');
  return lines.join('\n');
}

function kiroOutput(spec) {
  const tools = spec.capabilities.length === 1 && spec.capabilities[0] === '*'
    ? ['*']
    : spec.capabilities;
  const lines = [
    '---',
    `name: ${spec.name}`,
    `description: ${JSON.stringify(spec.description)}`,
    `tools: [${tools.join(', ')}]`,
  ];
  if (spec.providers?.kiro?.model) lines.push(`model: ${spec.providers.kiro.model}`);
  lines.push(
    '---',
    '',
    `<!-- ${GENERATED} -->`,
    '',
    spec.instructions.trim(),
    '',
  );
  return lines.join('\n');
}

function codexOutput(spec) {
  const writable = spec.capabilities.includes('*') || spec.capabilities.includes('write');
  return [
    `# ${GENERATED}`,
    `name = ${JSON.stringify(spec.name)}`,
    `description = ${JSON.stringify(spec.description)}`,
    `sandbox_mode = ${JSON.stringify(writable ? 'workspace-write' : 'read-only')}`,
    `developer_instructions = ${JSON.stringify(spec.instructions.trim())}`,
    '',
  ].join('\n');
}

function syncGenerated(specs, adoptedPaths) {
  const targets = [
    [join(ROOT, '.claude/agents'), '.md', claudeOutput],
    [join(ROOT, '.kiro/agents'), '.md', kiroOutput],
    [join(ROOT, '.codex/agents'), '.toml', codexOutput],
  ];
  const writes = [];
  const deletes = [];
  for (const [dir, extension, render] of targets) {
    const expectedNames = new Set();
    for (const { spec } of specs.values()) {
      const path = join(dir, `${spec.name}${extension}`);
      expectedNames.add(`${spec.name}${extension}`);
      const expected = render(spec);
      if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) {
        if (
          existsSync(path)
          && !readFileSync(path, 'utf8').includes(GENERATED)
          && !adoptedPaths.has(path)
        ) {
          issue(`${relative(ROOT, path)} は未管理の既存ファイルなので上書きしない`);
          continue;
        }
        if (WRITE) {
          writes.push({ path, content: expected });
        } else {
          issue(`${relative(ROOT, path)} が正本と同期していない`);
        }
      }
    }
    for (const path of filesUnder(dir, extension)) {
      if (expectedNames.has(path.slice(dir.length + 1))) continue;
      if (!readFileSync(path, 'utf8').includes(GENERATED)) continue;
      if (WRITE) {
        deletes.push(path);
      } else {
        issue(`${relative(ROOT, path)} に対応する正本がない`);
      }
    }
  }
  return { writes, deletes };
}

const skillPlan = normalizeSkills();
let specs = readSpecs(join(ROOT, '.agents/agents'));
const imported = importNewAgents(specs);
const generated = issues.length === 0 ? syncGenerated(specs, imported.adoptedPaths) : null;
const workflow = issues.length === 0 ? initWorkflowPlan() : null;

if (issues.length > 0) {
  console.error(`エージェント構成の${WRITE ? '補正' : '検査'}に失敗（${issues.length}件）:`);
  for (const message of issues) console.error(`  - ${message}`);
  if (!WRITE) console.error('\nnode scripts/sync-agent-layout.mjs --write で補正する。');
  process.exit(1);
}

if (WRITE) {
  // No filesystem mutation occurs until every source and generated target is validated.
  applySkillPlan(skillPlan);
  for (const { target, content, name } of imported.writes) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
    action(`${name} を .agents/agents に取り込み`);
  }
  for (const { path, content } of generated.writes) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    action(`${relative(ROOT, path)} を生成`);
  }
  for (const path of generated.deletes) {
    rmSync(path);
    action(`${relative(ROOT, path)} を削除`);
  }
  if (workflow) {
    mkdirSync(dirname(workflow.path), { recursive: true });
    writeFileSync(workflow.path, workflow.content);
    action(`${relative(ROOT, workflow.path)} を作成`);
  }
  console.log(actions.length ? actions.join('\n') : 'エージェント構成は同期済み');
} else {
  console.log('エージェント構成: 同期済み');
}
